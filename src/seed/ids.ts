/**
 * Идентификаторы для переноса из Obsidian.
 *
 * Обычные записи получают `ulid()` — случайный и разный при каждом вызове.
 * Здесь так нельзя: файл переноса загружают повторно (поправил название
 * в JSON, загрузил заново), и случайные id при втором заходе дали бы
 * девятнадцать позиций-дубликатов вместо девятнадцати исправленных.
 *
 * Поэтому id выводится из естественного ключа записи: у позиции — название,
 * у отметки — позиция и дата. Один и тот же вход даёт один и тот же id,
 * повторная загрузка сливается сама собой по общему правилу слияния.
 *
 * Форма остаётся ULID-совместимой (26 символов Crockford base32), чтобы
 * ничем не отличаться от записей, созданных приложением.
 */

const ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'

/**
 * Момент, которым помечаются все перенесённые записи.
 *
 * Одинаковый и неподвижный: любая правка в приложении получает `updatedAt`
 * позже этого, и при повторной загрузке файла побеждает правка, а не файл.
 * Перенос не может затереть то, что ты поправил руками.
 */
export const SEED_UPDATED_AT = '2026-09-08T00:00:00.000Z'

/**
 * 32-битный хеш строки, FNV-1a. Два разных семени дают две независимые
 * половины — вместе 64 бита, чего с запасом хватает на полторы сотни записей.
 *
 * `Math.imul` обязателен: обычное умножение уводит число за пределы точности
 * double и хеш перестаёт быть хешем.
 */
function hash32(key: string, seed: number): number {
  let value = seed
  for (let i = 0; i < key.length; i++) {
    value ^= key.charCodeAt(i)
    value = Math.imul(value, 16777619)
  }
  return value >>> 0
}

/** Число в base32 фиксированной длины, старшие разряды слева. */
function encode(value: number, length: number): string {
  let out = ''
  let rest = value
  for (let i = 0; i < length; i++) {
    out = (ALPHABET[rest % 32] ?? '0') + out
    rest = Math.floor(rest / 32)
  }
  return out
}

/**
 * Детерминированный id из естественного ключа.
 *
 * Первые 10 символов — время, как в ULID, одинаковое у всех перенесённых
 * записей: точного момента создания у них нет, а порядок внутри переноса
 * ничего не значит. Оставшиеся 16 — хеш ключа.
 */
export function seedId(key: string): string {
  const time = Date.parse(SEED_UPDATED_AT)
  return encode(time, 10) + encode(hash32(key, 0x811c9dc5), 8) + encode(hash32(key, 0x01000193), 8)
}
